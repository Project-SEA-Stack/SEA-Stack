"""Generate the Wigley support vessel for the crane flexible-jib demo.

Reuses the parametric Wigley hull builder from the wigley demo so geometry
cannot drift between demos.  Produces:

  meshes/vessel.nemoh   -- closed hull for Capytaine (clipped with immersed_part)
  geometry/vessel_hull.obj
  geometry/vessel_topsides.obj  -- crude wheelhouse / deck-house boxes
  vessel_metadata.yaml

Coordinate convention (body-local, BEM frame):
    x  longitudinal, bow at -L/2, stern at +L/2
    y  transverse, starboard positive
    z  vertical, waterline at 0, keel at -T, deck at +F

Usage:
    python generate_vessel.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Single source of truth for Wigley hull geometry.
_WIGLEY_ASSETS = Path(__file__).resolve().parents[2] / "wigley" / "assets"
if str(_WIGLEY_ASSETS) not in sys.path:
    sys.path.insert(0, str(_WIGLEY_ASSETS))

try:
    from generate_meshes import build_hull_mesh, write_nemoh, write_obj  # type: ignore
except ImportError as exc:  # pragma: no cover
    raise ImportError(
        f"Could not import Wigley hull builder from {_WIGLEY_ASSETS}.\n"
        "Expected data/demos/run_seastack/wigley/assets/generate_meshes.py."
    ) from exc

# ---------------------------------------------------------------------------
# Hull geometry -- must match run_bem.py and vessel_metadata.yaml
# ---------------------------------------------------------------------------
LENGTH = 50.0
BEAM = 12.0
DRAFT = 3.5
FREEBOARD = 3.5
COG_Z = -1.75

N_LONGITUDINAL = 48
N_UNDERWATER = 12
N_TOPSIDES = 6
N_DECK_TRANSVERSE = 8

# Crane seat on aft deck (body-local, deck at z = +FREEBOARD).
CRANE_SEAT_BODY_LOCAL = (15.0, 0.0, 5.25)

# Offshore platform deck placement in world / BEM frame.
PLATFORM_DECK_WORLD = (20.0, 16.0, 8.0)
WATER_DEPTH_M = 40.0


def _write_box_obj(
    path: Path,
    *,
    xmin: float,
    xmax: float,
    ymin: float,
    ymax: float,
    zmin: float,
    zmax: float,
    header: str,
) -> None:
    """Write a rectangular box as six quad faces (Wavefront OBJ)."""
    corners = [
        (xmin, ymin, zmin),
        (xmax, ymin, zmin),
        (xmax, ymax, zmin),
        (xmin, ymax, zmin),
        (xmin, ymin, zmax),
        (xmax, ymin, zmax),
        (xmax, ymax, zmax),
        (xmin, ymax, zmax),
    ]
    faces = [
        (1, 2, 3, 4),   # bottom
        (5, 6, 7, 8),   # top
        (1, 2, 6, 5),   # starboard
        (2, 3, 7, 6),   # forward (bow side of box)
        (3, 4, 8, 7),   # port
        (4, 1, 5, 8),   # aft
    ]
    with open(path, "w") as f:
        f.write(f"# {header}\n")
        for x, y, z in corners:
            f.write(f"v {x:.6f} {y:.6f} {z:.6f}\n")
        for v0, v1, v2, v3 in faces:
            f.write(f"f {v0} {v1} {v2} {v3}\n")


def build_topsides_obj(output_dir: Path) -> None:
    """Forward wheelhouse only — aft deck stays clear for the crane.

    Deck elevation z = +FREEBOARD (= 3.5 m). Wheelhouse near the bow
    (negative x), light superstructure with a darker glazing band.
    """
    geom_dir = output_dir / "geometry"
    deck_z = FREEBOARD

    _write_box_obj(
        geom_dir / "vessel_topsides.obj",
        xmin=-22.0,
        xmax=-12.0,
        ymin=-2.6,
        ymax=2.6,
        zmin=deck_z,
        zmax=deck_z + 4.0,
        header=f"Forward wheelhouse (deck z={deck_z:.1f} m); aft deck clear for crane",
    )
    # Bridge wing / glazing cap.
    cap = (
        (-21.5, -2.8, deck_z + 2.6),
        (-12.5, -2.8, deck_z + 2.6),
        (-12.5, 2.8, deck_z + 2.6),
        (-21.5, 2.8, deck_z + 2.6),
        (-21.5, -2.8, deck_z + 4.4),
        (-12.5, -2.8, deck_z + 4.4),
        (-12.5, 2.8, deck_z + 4.4),
        (-21.5, 2.8, deck_z + 4.4),
    )
    with open(geom_dir / "vessel_topsides.obj", "a") as f:
        f.write("# Bridge cap\n")
        base = 8
        for x, y, z in cap:
            f.write(f"v {x:.6f} {y:.6f} {z:.6f}\n")
        faces = [
            (base + 1, base + 2, base + 3, base + 4),
            (base + 5, base + 6, base + 7, base + 8),
            (base + 1, base + 2, base + 6, base + 5),
            (base + 2, base + 3, base + 7, base + 6),
            (base + 3, base + 4, base + 8, base + 7),
            (base + 4, base + 1, base + 5, base + 8),
        ]
        for v0, v1, v2, v3 in faces:
            f.write(f"f {v0} {v1} {v2} {v3}\n")


def write_vessel_metadata(output_dir: Path) -> None:
    """Write crane-demo vessel metadata consumed by the model YAML."""
    path = output_dir / "vessel_metadata.yaml"
    gap_x = PLATFORM_DECK_WORLD[0] - LENGTH / 2.0
    gap_y = PLATFORM_DECK_WORLD[1]
    text = f"""# Crane flexible-jib demo -- support vessel metadata
# Generated by generate_vessel.py; edit the script, not this file, to change geometry.

units: m/SI
axes: z-up, waterline z=0

hull:
  length_m: {LENGTH}
  beam_m: {BEAM}
  draft_m: {DRAFT}
  freeboard_m: {FREEBOARD}
  cog_z: {COG_Z}
  hull_to_body_z_offset: {FREEBOARD - COG_Z:.2f}  # deck z - cog_z in body frame

crane_seat_body_local: [{CRANE_SEAT_BODY_LOCAL[0]}, {CRANE_SEAT_BODY_LOCAL[1]}, {CRANE_SEAT_BODY_LOCAL[2]}]

platform:
  deck_world: [{PLATFORM_DECK_WORLD[0]}, {PLATFORM_DECK_WORLD[1]}, {PLATFORM_DECK_WORLD[2]}]
  gap_notes: >
    Platform centre at ({PLATFORM_DECK_WORLD[0]:.1f}, {PLATFORM_DECK_WORLD[1]:.1f}) m
    world/BEM frame.  Approx. {gap_x:.1f} m aft of vessel stern (x=+L/2={LENGTH / 2:.1f})
    and {gap_y:.1f} m to starboard of centreline.  ~{((gap_x ** 2 + gap_y ** 2) ** 0.5):.1f} m
    centre-to-centre offset; crane boom must span the gap for lift-off.

sea_state:
  water_depth_m: {WATER_DEPTH_M}
"""
    path.write_text(text, encoding="utf-8")
    print(f"  YAML:  {path.name}")


def generate(output_dir: Path) -> None:
    meshes_dir = output_dir / "geometry"
    geom_dir = output_dir / "geometry"
    mesh_out = output_dir / "meshes"
    meshes_dir.mkdir(parents=True, exist_ok=True)
    geom_dir.mkdir(parents=True, exist_ok=True)
    mesh_out.mkdir(parents=True, exist_ok=True)

    vertices, quads = build_hull_mesh(
        LENGTH, BEAM, DRAFT, FREEBOARD,
        N_LONGITUDINAL, N_UNDERWATER, N_TOPSIDES, N_DECK_TRANSVERSE,
        cosine_x=True,
    )

    nemoh_path = mesh_out / "vessel.nemoh"
    write_nemoh(nemoh_path, vertices, quads)
    print(f"  Nemoh: {nemoh_path.name}  ({len(vertices)} verts, {len(quads)} panels)")

    hull_path = geom_dir / "vessel_hull.obj"
    write_obj(hull_path, vertices, quads, header="Crane demo vessel, closed Wigley hull")
    print(f"  OBJ:   {hull_path.name}")

    build_topsides_obj(output_dir)
    print(f"  OBJ:   vessel_topsides.obj")

    write_vessel_metadata(output_dir)

    rho = 1025.0
    vol = 4.0 * LENGTH * BEAM * DRAFT / 9.0
    mass = rho * vol
    print("\n--- Vessel summary ---")
    print(f"  L x B x T x F:      {LENGTH} x {BEAM} x {DRAFT} x {FREEBOARD} m")
    print(f"  CoG (BEM):          z = {COG_Z} m")
    print(f"  Crane seat (local): {CRANE_SEAT_BODY_LOCAL}")
    print(f"  Platform deck:      {PLATFORM_DECK_WORLD}")
    print(f"  Displaced volume:   {vol:.2f} m^3")
    print(f"  Equilibrium mass:   {mass:.0f} kg")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--output-dir", type=Path, default=None)
    args = ap.parse_args()

    print("Generating crane demo vessel assets...\n")
    generate(args.output_dir or Path(__file__).resolve().parent)
    print("\nDone.")


if __name__ == "__main__":
    main()
